import os
import random
from datetime import datetime

import streamlit as st
import torch
from diffusers import StableDiffusionPipeline

st.set_page_config(
    page_title="VisionGen AI",
    page_icon="🧠",
    layout="wide"
)

MODEL_ID = "runwayml/stable-diffusion-v1-5"

@st.cache_resource
def load_pipeline():
    device = "cuda" if torch.cuda.is_available() else "cpu"
    dtype = torch.float16 if device == "cuda" else torch.float32

    pipe = StableDiffusionPipeline.from_pretrained(
        MODEL_ID,
        torch_dtype=dtype
    )
    pipe = pipe.to(device)

    if device == "cuda":
        pipe.enable_attention_slicing()

    return pipe, device

st.title("🧠 VisionGen AI")
st.subheader("Generative AI for Computer Vision — Text-to-Image Generation")

st.markdown(
    "Enter a natural-language description and generate a synthetic image "
    "using a pretrained diffusion model."
)

with st.sidebar:
    st.header("Generation Settings")

    steps = st.slider(
        "Inference steps",
        min_value=10,
        max_value=50,
        value=25,
        step=5
    )

    width = st.selectbox(
        "Width",
        [256, 384, 512],
        index=2
    )

    height = st.selectbox(
        "Height",
        [256, 384, 512],
        index=2
    )

    seed = st.number_input(
        "Seed",
        min_value=0,
        max_value=999999,
        value=42,
        step=1
    )

    st.info(
        "Tip: descriptive prompts with subject, environment, "
        "lighting and style usually produce more controllable results."
    )

prompt = st.text_area(
    "Enter your prompt",
    value=(
        "A futuristic autonomous vehicle analyzing a smart city street, "
        "computer vision sensors, cinematic lighting, highly detailed"
    ),
    height=100
)

negative_prompt = st.text_input(
    "Negative prompt",
    value="blurry, distorted, low quality, duplicate objects"
)

generate = st.button("✨ Generate Image", type="primary")

if generate:
    if not prompt.strip():
        st.warning("Please enter a prompt.")
        st.stop()

    with st.spinner("Loading model and generating image..."):
        try:
            pipe, device = load_pipeline()

            generator = torch.Generator(device=device).manual_seed(int(seed))

            result = pipe(
                prompt=prompt,
                negative_prompt=negative_prompt,
                num_inference_steps=steps,
                width=width,
                height=height,
                generator=generator
            )

            image = result.images[0]

            os.makedirs("generated", exist_ok=True)
            timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
            output_path = os.path.join(
                "generated",
                f"visiongen_{timestamp}.png"
            )
            image.save(output_path)

            col1, col2 = st.columns([2, 1])

            with col1:
                st.image(
                    image,
                    caption="Generated by VisionGen AI",
                    use_container_width=True
                )

            with col2:
                st.success("Generation complete!")
                st.write(f"**Device:** {device.upper()}")
                st.write(f"**Steps:** {steps}")
                st.write(f"**Seed:** {seed}")
                st.write(f"**Resolution:** {width} × {height}")

                with open(output_path, "rb") as f:
                    st.download_button(
                        "⬇️ Download Image",
                        data=f,
                        file_name=os.path.basename(output_path),
                        mime="image/png"
                    )

        except Exception as exc:
            st.error("Generation failed.")
            st.exception(exc)

st.divider()

st.markdown("### 🔬 Computer Vision Connection")
st.write(
    "Generative AI can be viewed as the reverse side of computer vision: "
    "instead of only interpreting visual information, a generative model "
    "learns the visual distribution and produces new visual content."
)

st.markdown("### 🎓 Viva Questions")
with st.expander("Why is Stable Diffusion called a diffusion model?"):
    st.write(
        "It learns to reverse a gradual noising process. During generation, "
        "the model starts from noise and repeatedly denoises it into a coherent image."
    )

with st.expander("Why use a pretrained model?"):
    st.write(
        "Training a large text-to-image model requires enormous datasets, "
        "compute resources and time. A pretrained model makes the concept "
        "practical for an academic demonstration."
    )

with st.expander("What is the role of the prompt?"):
    st.write(
        "The prompt provides textual conditioning that guides the model "
        "toward visual concepts matching the requested description."
    )
